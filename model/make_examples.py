"""Builds what the matcher is trained and tested on, from the datasets already on the site.

The matcher's job: read a question in everyday words and say which variable on the site it is asking for.
Nothing here is scraped. Every example is made from the site's own list of datasets (docs/data/datasets.json),
so each one points at a real variable with a known source and licence.

Writes, in model/out/:
  variables.jsonl        every numeric variable on the site, with the text the model reads for it
  train.jsonl            questions made from templates for the sustainability and policy variables
  test_synthetic.jsonl   questions made from other templates and wordings, kept out of training
  test_natural.jsonl     the hand-written questions in natural_questions.tsv, never used for training

Run:  python model/make_examples.py
"""
import difflib
import json
import pathlib
import random
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "model" / "out"

# The datasets the model is trained on: sustainability in its three parts (the planet, people, the economy's basics) and policy.
FOCUS = [
    # climate, energy and the environment
    "co2-and-greenhouse-gases", "energy", "emissions-by-sector", "climate-trace-emissions", "climate-and-environment-policy",
    "environment-indicators", "forests-wildlife-and-plastic", "natural-disasters", "renewable-capacity", "global-temperature",
    "atmospheric-co2", "us-climate-monthly", "biodiversity-records-by-country", "biodiversity-records-by-year",
    "us-ev-charging-stations", "us-river-flow-monthly",
    # food and land
    "food-and-agriculture", "food-supply", "us-crop-production",
    # people: the social side of sustainable development
    "world-bank-development", "human-development-index", "poverty-and-inequality", "health-indicators", "who-health-observatory",
    "education-indicators", "gender-indicators", "labour-indicators", "un-population", "wellbeing-and-schooling", "top-incomes",
    # policy and government
    "governance-indicators", "democracy-and-rights", "conflict-and-security", "trade-and-finance", "us-federal-register",
    "us-congress-and-rulemaking", "us-disaster-declarations",
]

PLACES = ["India", "China", "the United States", "Germany", "Brazil", "Nigeria", "Japan", "France", "the UK", "Indonesia", "South Africa",
          "Kenya", "Mexico", "Canada", "Australia", "Russia", "Bangladesh", "Egypt", "Turkey", "Vietnam", "Pakistan", "Ethiopia",
          "Saudi Arabia", "Argentina", "Poland", "Sweden", "Norway", "Spain", "Italy", "South Korea", "Thailand", "Colombia", "Ghana",
          "Chile", "Peru", "Nepal", "the world", "Europe", "Africa", "the Netherlands"]

TRAIN = ["{p}", "{p} {c}", "{c} {p}", "{p} in {c}", "What is {p} in {c}?", "what's the {p} for {c}", "{p} {c} {y}", "{p} in {c} in {y}",
         "How has {p} changed in {c}?", "{p} over time", "history of {p} in {c}", "chart {p} {c}", "Which countries have the highest {p}?",
         "top 10 countries by {p}", "lowest {p}", "compare {p} for {c} and {c2}", "{c} vs {c2} {p}", "map of {p}", "trend in {p} since {y}",
         "how much {p} does {c} have", "tell me about {p} in {c}", "{p} by country", "show {p} for {c} since {y}", "is {p} rising in {c}?",
         "which country leads in {p}"]
TEST = ["Can you give me {p} for {c}?", "I need data on {p} in {c}", "{c}: {p}, latest figure", "how does {c} rank on {p}",
        "what was {p} in {c} back in {y}", "who has the most {p}", "{p}, {c} compared with {c2}", "plot {p} for {c} from {y}",
        "has {p} gone up or down in {c}", "figures for {p} worldwide"]

# Other ways people say the same thing. Each rule that fits a title gives one more wording.
SWAPS = [(r"CO₂", "CO2"), (r"CO₂", "carbon dioxide"), (r"\bCO2\b", "carbon"), (r"per capita", "per person"), (r"per person", "per capita"),
         (r"per person", "per head"), (r"^Share of electricity generated by (.+)$", r"how much electricity comes from \1"),
         (r"^Share of (.+)$", r"percentage of \1"), (r"\belectricity\b", "power"), (r"\bGDP\b", "economic output"), (r"greenhouse gas", "GHG"),
         (r"^Annual ", ""), (r"^Total ", ""), (r"\bconsumption\b", "use"), (r"primary energy", "energy"),
         (r"Life expectancy at birth", "life expectancy"), (r"\bmortality rate\b", "death rate"), (r"\bemissions\b", "pollution"),
         (r"\brenewables\b", "renewable energy"), (r"\bindex\b", "score"), (r"\bprevalence of\b", "how common is"), (r"\bfemale\b", "women"),
         (r"\bmale\b", "men"), (r"\bexpenditure\b", "spending"), (r"\bpopulation\b", "number of people"), (r"\bprotected areas\b", "protected land"),
         (r"\bsubsidies\b", "government support"), (r"\bdeforestation\b", "forest loss")]


def first_sentence(text):
    s = re.split(r"(?<=[.!?])\s", (text or "").strip())[0]
    return s if 20 <= len(s) <= 160 else ""


def variables():
    """Every numeric variable on the site."""
    out = []
    for d in json.loads((ROOT / "docs/data/datasets.json").read_text())["datasets"]:
        for c in d["columns"]:
            if c.get("type") != "num":
                continue
            desc = first_sentence(c.get("description"))
            out.append({"id": f'{d["id"]}::{c["name"]}', "dataset": d["id"], "name": c["name"], "title": c["title"], "unit": c.get("unit") or "",
                        "by_place": d["keys"] == ["code", "year"], "focus": d["id"] in FOCUS,
                        "key": re.sub(r"[^a-z0-9]+", " ", c["title"].lower().replace("₂", "2")).strip(),   # the same title in two datasets is the same measure
                        "doc": f'{c["title"]}. {desc} Unit: {c.get("unit") or "none"}. From: {d["title"]}'.replace("  ", " ")})
    return out


def lower_first(s):
    return s if len(s) < 2 or s[1].isupper() or not s[0].isupper() else s[0].lower() + s[1:]


def phrases(v):
    """Different wordings of one variable, the plainest first."""
    base = re.sub(r"\s*\([^)]*\)", "", v["title"]).strip() or v["title"]
    out = [v["title"], base]
    for pattern, new in SWAPS:
        alt = re.sub(pattern, new, base, flags=re.I)
        if alt != base:
            out.append(alt)
    desc = first_sentence(v["doc"].split(". ", 1)[1] if ". " in v["doc"] else "")
    words = lambda t: {w for w in re.findall(r"[a-z]{4,}", t.lower())}
    if desc and not re.match(r"(Measured|Unit|From)\b", desc) and words(desc) & words(base):   # only a sentence that is about the measure itself
        out.append(desc.rstrip("."))
    out.append(v["name"].replace("_", " "))
    seen, keep = set(), []
    for p in out:
        p = lower_first(p.strip())
        if p and p.lower() not in seen:
            seen.add(p.lower()); keep.append(p)
    return keep


def ask(template, phrase, rng, by_place):
    c, c2 = rng.sample(PLACES, 2)
    q = template.format(p=phrase, c=c, c2=c2, y=rng.choice(range(1990, 2025)))
    if not by_place:                                           # a single series has no country to name
        q = re.sub(r"\s+(in|for|of)\s+(the\s+)?[A-Z][\w ]+?(?=(\?|$|,| since| from| back| and| in \d))", "", q)
        for place in PLACES:
            q = q.replace(place, "")
        q = re.sub(r"\s{2,}", " ", q).replace(" ,", ",").replace(" ?", "?").strip(" ,:")
    return q


def main():
    rng = random.Random(7)
    V = variables()
    by_id = {v["id"]: v for v in V}
    same = {}
    for v in V:
        same.setdefault(v["key"], []).append(v["id"])
    train, synth = [], []
    for v in (v for v in V if v["focus"]):
        P = phrases(v)
        held = rng.choice(P[1:]) if len(P) >= 3 else None       # one wording is kept back for the test
        for p in P:
            if p == held:
                continue
            for t in rng.sample(TRAIN, 5 if p in P[:2] else 3):
                train.append({"q": ask(t, p, rng, v["by_place"]), "id": v["id"]})
        synth.append({"q": ask(rng.choice(TEST), held or P[0], rng, v["by_place"]), "gold": same[v["key"]], "id": v["id"]})

    natural, unknown, waiting = [], [], 0
    datasets = {v["dataset"] for v in V}
    for line in (ROOT / "model/natural_questions.tsv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        q, ids = line.split("\t")
        ids = ids.split("|")
        if any(i.split("::")[0] not in datasets for i in ids):   # a dataset that is not on the site yet: the question waits for it
            waiting += 1
            continue
        for i in ids:
            if i not in by_id:
                near = difflib.get_close_matches(i.split("::")[1], [v["name"] for v in V if v["dataset"] == i.split("::")[0]], 4, 0.3)
                unknown.append(f"{i}  (closest: {', '.join(near)})")
        gold = sorted({g for i in ids if i in by_id for g in same[by_id[i]["key"]]})
        natural.append({"q": q, "gold": gold})
    if unknown:
        sys.exit("These answers in natural_questions.tsv are not variables on the site:\n  " + "\n  ".join(unknown))

    OUT.mkdir(parents=True, exist_ok=True)
    rng.shuffle(train)
    for name, rows in (("variables", [{k: v[k] for k in ("id", "key", "doc", "focus")} for v in V]), ("train", train),
                       ("test_synthetic", synth), ("test_natural", natural)):
        (OUT / f"{name}.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    focus = [v for v in V if v["focus"]]
    print(f"{len(V)} numeric variables on the site, {len(focus)} of them in {len({v['dataset'] for v in focus})} sustainability and policy datasets")
    print(f"{len(train)} training questions, {len(synth)} held-out synthetic questions, {len(natural)} hand-written questions"
          + (f" ({waiting} more wait for a dataset that is not on the site yet)" if waiting else ""))
    for r in rng.sample(train, 6):
        print("  train:", r["q"], "->", r["id"])
    for r in rng.sample(synth, 4):
        print("  test: ", r["q"], "->", r["id"])


if __name__ == "__main__":
    main()
